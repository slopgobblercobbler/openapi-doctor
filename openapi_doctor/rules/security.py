"""Rule to detect and autofix security scheme mismatches and undefined security schemes."""

from __future__ import annotations

from typing import Any, Dict, List, Set

from openapi_doctor.models import Diagnostic, FixAction, RuleId, Severity
from openapi_doctor.parser import ParsedSpec, escape_pointer_token
from openapi_doctor.rules.base import BaseRule, iter_operations


def generate_security_scheme_stub(name: str) -> Dict[str, Any]:
    """Generates an appropriate stub security scheme definition based on name heuristics."""
    lower_name = name.lower()
    if "api" in lower_name or "key" in lower_name:
        return {
            "type": "apiKey",
            "name": "X-API-Key",
            "in": "header",
            "description": f"Autogenerated API key security scheme for '{name}'",
        }
    elif "basic" in lower_name:
        return {
            "type": "http",
            "scheme": "basic",
            "description": f"Autogenerated Basic auth security scheme for '{name}'",
        }
    elif "oauth" in lower_name:
        return {
            "type": "oauth2",
            "description": f"Autogenerated OAuth2 security scheme for '{name}'",
            "flows": {
                "clientCredentials": {
                    "tokenUrl": "https://example.com/oauth/token",
                    "scopes": {},
                }
            },
        }
    else:
        return {
            "type": "http",
            "scheme": "bearer",
            "bearerFormat": "JWT",
            "description": f"Autogenerated HTTP Bearer security scheme for '{name}'",
        }


class SecuritySchemeMismatchRule(BaseRule):
    """
    Validates security scheme usage:
    1. Checks that all security scheme names referenced in root or operation `security`
       exist in `components.securitySchemes`.
    2. Checks that OAuth2/OpenID scopes referenced in `security` are defined in the scheme's flows.
    Autofixes by creating missing security scheme stubs and registering missing scopes.
    """

    rule_id = RuleId.UNDEFINED_SECURITY_SCHEME
    default_severity = Severity.ERROR
    description = "Security requirement references an undefined security scheme or invalid scope."

    def handles_rule_id(self, rule_id: str) -> bool:
        return rule_id in (
            RuleId.UNDEFINED_SECURITY_SCHEME,
            RuleId.INVALID_SECURITY_SCOPE,
        )

    def check(self, spec: ParsedSpec, context: Dict[str, Any]) -> List[Diagnostic]:
        diagnostics: List[Diagnostic] = []
        components = spec.data.get("components")
        sec_schemes: Dict[str, Any] = {}
        if isinstance(components, dict):
            raw_schemes = components.get("securitySchemes")
            if isinstance(raw_schemes, dict):
                sec_schemes = raw_schemes

        already_stubbed_schemes: Set[str] = set()

        def inspect_security_requirement(
            sec_list: Any,
            location_label: str,
            base_pointer: str,
        ) -> None:
            if not isinstance(sec_list, list):
                return

            for req_idx, req in enumerate(sec_list):
                if not isinstance(req, dict):
                    continue

                for scheme_name, scopes in req.items():
                    req_pointer = f"{base_pointer}/{req_idx}/{escape_pointer_token(scheme_name)}"
                    line, col = spec.get_location(req_pointer)

                    # Check 1: Scheme existence
                    if scheme_name not in sec_schemes and scheme_name not in already_stubbed_schemes:
                        already_stubbed_schemes.add(scheme_name)
                        stub = generate_security_scheme_stub(scheme_name)
                        target_ptr = f"/components/securitySchemes/{escape_pointer_token(scheme_name)}"

                        fix_action = FixAction(
                            rule_id=RuleId.UNDEFINED_SECURITY_SCHEME,
                            description=f"Create stub security scheme for '{scheme_name}' in components.securitySchemes",
                            target_pointer=target_ptr,
                            action_type="set",
                            value=stub,
                        )

                        diagnostics.append(
                            Diagnostic(
                                rule_id=RuleId.UNDEFINED_SECURITY_SCHEME,
                                message=f"Security scheme '{scheme_name}' used in {location_label} is not defined in 'components.securitySchemes'.",
                                severity=Severity.ERROR,
                                pointer=req_pointer,
                                line=line,
                                column=col,
                                fixable=True,
                                fix_action=fix_action,
                                suggestion=f"Define '{scheme_name}' in components.securitySchemes",
                            )
                        )

                    # Check 2: Scopes for OAuth2 / OpenIdConnect schemes
                    elif scheme_name in sec_schemes and isinstance(scopes, list) and scopes:
                        scheme_def = sec_schemes[scheme_name]
                        if isinstance(scheme_def, dict) and scheme_def.get("type") in ("oauth2", "openIdConnect"):
                            flows = scheme_def.get("flows")
                            if isinstance(flows, dict):
                                # Gather existing scopes across all flows
                                existing_scopes: Set[str] = set()
                                primary_flow_key = None
                                for f_key, flow in flows.items():
                                    if isinstance(flow, dict):
                                        if primary_flow_key is None:
                                            primary_flow_key = f_key
                                        f_scopes = flow.get("scopes")
                                        if isinstance(f_scopes, dict):
                                            existing_scopes.update(f_scopes.keys())

                                for scope in scopes:
                                    if scope not in existing_scopes and primary_flow_key:
                                        scope_pointer = f"/components/securitySchemes/{escape_pointer_token(scheme_name)}/flows/{primary_flow_key}/scopes/{escape_pointer_token(scope)}"
                                        fix_action = FixAction(
                                            rule_id=RuleId.INVALID_SECURITY_SCOPE,
                                            description=f"Add missing scope '{scope}' to security scheme '{scheme_name}'",
                                            target_pointer=scope_pointer,
                                            action_type="set",
                                            value=f"Grants access to {scope}",
                                        )

                                        diagnostics.append(
                                            Diagnostic(
                                                rule_id=RuleId.INVALID_SECURITY_SCOPE,
                                                message=f"Scope '{scope}' used in {location_label} for '{scheme_name}' is not declared in its flows.",
                                                severity=Severity.WARNING,
                                                pointer=req_pointer,
                                                line=line,
                                                column=col,
                                                fixable=True,
                                                fix_action=fix_action,
                                                suggestion=f"Declare scope '{scope}' in flows for '{scheme_name}'",
                                            )
                                        )

        # Check Root Security
        inspect_security_requirement(spec.data.get("security"), "root specification", "/security")

        # Check Operation Security
        for path, method, op, op_pointer in iter_operations(spec.data):
            inspect_security_requirement(op.get("security"), f"{method.upper()} {path}", f"{op_pointer}/security")

        return diagnostics
