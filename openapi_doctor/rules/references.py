"""Rule to detect and autofix broken $ref references and undefined schemas."""

from __future__ import annotations

from typing import Any, Dict, Iterator, List, Tuple

from openapi_doctor.models import Diagnostic, FixAction, RuleId, Severity
from openapi_doctor.parser import (
    ParsedSpec,
    pointer_to_tokens,
    resolve_pointer,
    tokens_to_pointer,
)
from openapi_doctor.rules.base import BaseRule


def walk_references(node: Any, tokens: List[str]) -> Iterator[Tuple[str, str, List[str]]]:
    """
    Recursively walks the document tree yielding (ref_value, pointer, tokens).
    """
    if isinstance(node, dict):
        if "$ref" in node and isinstance(node["$ref"], str):
            ref_tokens = list(tokens) + ["$ref"]
            yield node["$ref"], tokens_to_pointer(ref_tokens), tokens
        for key, val in node.items():
            yield from walk_references(val, list(tokens) + [key])
    elif isinstance(node, list):
        for idx, item in enumerate(node):
            yield from walk_references(item, list(tokens) + [str(idx)])


class UndefinedSchemaRule(BaseRule):
    """
    Detects unresolved internal $ref references (e.g. #/components/schemas/NonExistent).
    Autofixes broken schema references by generating stub schema components.
    """

    rule_id = RuleId.BROKEN_REF
    default_severity = Severity.ERROR
    description = "Internal $ref pointer target does not exist in the specification."

    def handles_rule_id(self, rule_id: str) -> bool:
        return rule_id in (
            RuleId.BROKEN_REF,
            RuleId.UNDEFINED_SCHEMA,
        )

    def check(self, spec: ParsedSpec, context: Dict[str, Any]) -> List[Diagnostic]:
        diagnostics: List[Diagnostic] = []

        for ref_val, ref_pointer, parent_tokens in walk_references(spec.data, []):
            if not ref_val.startswith("#/"):
                # External references (URLs, files) are skipped or validated separately
                continue

            exists, _ = resolve_pointer(spec.data, ref_val)
            if not exists:
                line, col = spec.get_location(ref_pointer)
                ref_parts = pointer_to_tokens(ref_val)

                # Determine if we can generate a stub
                fixable = False
                fix_action = None
                suggestion = None

                if len(ref_parts) == 3 and ref_parts[0] == "components":
                    section = ref_parts[1]
                    item_name = ref_parts[2]

                    if section == "schemas":
                        stub_schema = {
                            "type": "object",
                            "description": f"Autogenerated stub schema for {item_name}",
                            "properties": {},
                        }
                        target_pointer = f"/components/schemas/{item_name}"
                        fixable = True
                        suggestion = f"Create stub schema '#/components/schemas/{item_name}'"
                        fix_action = FixAction(
                            rule_id=self.rule_id,
                            description=f"Create stub schema for '{item_name}' in components.schemas",
                            target_pointer=target_pointer,
                            action_type="set",
                            value=stub_schema,
                        )
                    elif section == "responses":
                        stub_resp = {
                            "description": f"Autogenerated stub response for {item_name}",
                        }
                        target_pointer = f"/components/responses/{item_name}"
                        fixable = True
                        suggestion = f"Create stub response '#/components/responses/{item_name}'"
                        fix_action = FixAction(
                            rule_id=self.rule_id,
                            description=f"Create stub response for '{item_name}' in components.responses",
                            target_pointer=target_pointer,
                            action_type="set",
                            value=stub_resp,
                        )
                    elif section == "parameters":
                        stub_param = {
                            "name": item_name,
                            "in": "query",
                            "description": f"Autogenerated stub parameter for {item_name}",
                            "schema": {"type": "string"},
                        }
                        target_pointer = f"/components/parameters/{item_name}"
                        fixable = True
                        suggestion = f"Create stub parameter '#/components/parameters/{item_name}'"
                        fix_action = FixAction(
                            rule_id=self.rule_id,
                            description=f"Create stub parameter for '{item_name}' in components.parameters",
                            target_pointer=target_pointer,
                            action_type="set",
                            value=stub_param,
                        )

                diagnostics.append(
                    Diagnostic(
                        rule_id=self.rule_id,
                        message=f"Unresolved reference '{ref_val}'. Target definition does not exist.",
                        severity=self.default_severity,
                        pointer=ref_pointer,
                        line=line,
                        column=col,
                        fixable=fixable,
                        fix_action=fix_action,
                        suggestion=suggestion or f"Define missing component at '{ref_val}'",
                    )
                )

        return diagnostics
